// PixelForge -> Godot 4 portable gameplay adapter v1.
// Produces a bounded, explicit local project with a key-release visibility script.
// It never embeds arbitrary user code, purchased GLB bytes or runtime authority.
import {validateWorld} from './world.js';
import {validateGameplayBlueprint} from './gameplay-keys.js';
import {exportSceneForEngine} from './engine-export.js';
import {zipStore} from './godot-package.js';

const encode=value=>new TextEncoder().encode(value);
const KEYS=Object.freeze({e:'KEY_E',f:'KEY_F',space:'KEY_SPACE'});
const nodeName=index=>'Obj_'+String(index+1);

export function compileGodotVisibility(world,blueprint){
  const safe=validateGameplayBlueprint(world,blueprint);
  return Object.freeze({
    schema:'pixelforge.godot-key-visibility.v1',
    sourceSchema:safe.schema,worldFormat:safe.worldFormat,worldTitle:safe.worldTitle,
    rules:safe.rules.map(rule=>{
      const index=world.objects.findIndex(object=>object.id===rule.targetId);
      if(index<0)throw Error('Gameplay target missing.');
      return Object.freeze({
        id:rule.id,on:rule.on,key:rule.key,
        keycode:KEYS[rule.key],targetId:rule.targetId,
        nodeName:nodeName(index),visible:rule.effect==='show'
      });
    })
  });
}
export function renderGodotVisibilityScript(compiled){
  if(!compiled||compiled.schema!=='pixelforge.godot-key-visibility.v1'||
     !Array.isArray(compiled.rules)||compiled.rules.length<1||compiled.rules.length>12||
     compiled.rules.some(rule=>!rule||typeof rule!=='object'||
       !/^rule-[0-9]{3}$/.test(rule.id)||rule.on!=='keyReleased'||
       !Object.hasOwn(KEYS,rule.key)||rule.keycode!==KEYS[rule.key]||
       !/^obj-[1-9][0-9]{0,8}$/.test(rule.targetId)||
       !/^Obj_[1-9][0-9]{0,3}$/.test(rule.nodeName)||
       typeof rule.visible!=='boolean'))
    throw Error('Godot visibility script requires a compiled ruleset.');
  const lines=[
    'extends Node3D',
    '',
    '# Generated by PixelForge from a validated declarative visibility blueprint.',
    '# Operator-authored key releases only. No arbitrary scripts or external access.',
    'const RULES = [',
    ...compiled.rules.map(rule=>
      '    {"keycode": '+rule.keycode+', "target": "'+rule.nodeName+
      '", "visible": '+(rule.visible?'true':'false')+'},'),
    ']',
    '',
    'var _targets: Dictionary = {}',
    'var _active: bool = false',
    '',
    'func _ready() -> void:',
    '    for rule in RULES:',
    '        var path: String = rule["target"]',
    '        var target: Node3D = get_node_or_null(NodePath(path)) as Node3D',
    '        if target == null:',
    '            push_error("PixelForge visibility rules inactive: missing node " + path)',
    '            _targets.clear()',
    '            return',
    '        _targets[path] = target',
    '    _active = true',
    '',
    'func _unhandled_key_input(event: InputEvent) -> void:',
    '    if not _active or not event is InputEventKey:',
    '        return',
    '    var key_event: InputEventKey = event as InputEventKey',
    '    if key_event.pressed or key_event.echo:',
    '        return',
    '    if key_event.ctrl_pressed or key_event.alt_pressed or key_event.meta_pressed:',
    '        return',
    '    for rule in RULES:',
    '        if key_event.keycode != rule["keycode"]:',
    '            continue',
    '        var target: Node3D = _targets[rule["target"]] as Node3D',
    '        if target != null:',
    '            target.visible = rule["visible"]',
    ''
  ];
  return lines.join('\n');
}

export function exportGodotVisibilityProject(world,settings={}){
  validateWorld(world);
  if(!settings||typeof settings!=='object'||Array.isArray(settings)||
     Object.keys(settings).some(key=>!['behavior','allowPlaceholders'].includes(key))||
     (settings.allowPlaceholders!==undefined&&typeof settings.allowPlaceholders!=='boolean')||
     settings.behavior===undefined)
    throw Error('Invalid Godot gameplay export settings.');
  const behavior=compileGodotVisibility(world,settings.behavior);
  const proxies=world.objects.filter(object=>object.kind==='asset-proxy');
  if(proxies.length && settings.allowPlaceholders!==true)
    throw Error('Private GLB mesh data is NOT bundled; explicitly approve placeholder cuboids.');
  const original=exportSceneForEngine(world,'godot4',{allowPlaceholders:settings.allowPlaceholders===true});
  // Add one external resource and attach it to the existing scene root. The source
  // exporter and canonical PixelForge world never change.
  let scene=original.content;
  const header=/^\[gd_scene load_steps=(\d+) format=3\]\n/;
  if(!header.test(scene))throw Error('Unrecognized Godot scene header.');
  scene=scene.replace(header,(_,count)=>
    '[gd_scene load_steps='+String(Number(count)+1)+' format=3]\n'+
    '\n[ext_resource type="Script" path="res://scripts/visibility_rules.gd" id="PFBehavior"]\n');
  const root='[node name="PixelForgeWorld" type="Node3D"]';
  if(scene.split(root).length!==2)throw Error('Unrecognized Godot root node.');
  scene=scene.replace(root,root+'\nscript = ExtResource("PFBehavior")');
  scene+=[
    '[node name="PreviewCamera" type="Camera3D" parent="."]',
    'position = Vector3(0, 6, 16)',
    'rotation = Vector3(-0.27, 0, 0)',
    'current = true',
    '',
    '[node name="PreviewSun" type="DirectionalLight3D" parent="."]',
    'rotation = Vector3(-0.65, -0.45, 0)',
    'light_energy = 1.0',
    ''
  ].join('\n');
  const script=renderGodotVisibilityScript(behavior);
  const manifest={
    schema:'pixelforge.godot-gameplay-pack.v1',
    worldFormat:world.format,sourceTitle:world.title,
    status:'GODOT_INTERACTION_PROJECT_GENERATED_EDITOR_UNVERIFIED',
    objectCount:world.objects.length,placeholderCount:proxies.length,
    behavior,
    sourceObjects:world.objects.map((object,index)=>({
      sourceId:object.id,nodeName:nodeName(index),
      kind:object.kind,placeholderOnly:object.kind==='asset-proxy'
    })),
    limits:[
      'Godot 4 Editor import and actual key handling NOT verified by CI',
      'No third-party GLB model bytes or purchased textures included',
      'Key release show/hide only: no physics, collision, NPCs, quests, save/load, movement or VR'
    ]
  };
  const readme=[
    '# PixelForge to Godot 4: visibility interaction preview',
    '',
    'This ZIP contains static cuboid geometry and a bounded, generated GDScript.',
    'Extract into a NEW folder and open project.godot in Godot 4.x.',
    'Run the main scene (F6 or F5) with the editor and use the rule key to show/hide the chosen object.',
    'A fixed camera and directional light are provided for visual inspection.',
    'Input: release E, F or Space with no Ctrl/Alt/Meta modifiers.',
    '',
    'The canonical world is unchanged. Rules are in gameplay.json; targets use',
    'stable source IDs converted into Obj_1, Obj_2, etc as recorded in manifest.json.',
    'Missing target nodes cause all keyboard handlers to remain inactive.',
    'Imported private GLB files are NOT bundled. Approved proxies become placeholder cuboids.',
    '',
    'Not a Godot runtime acceptance receipt: open the project in the real editor',
    'and verify camera, parser, and show/hide keyboard behavior before production.',
    'No player controller, movement, collision, physics, AI, quests or XR support.',
    ''
  ].join('\n');
  const entries=[
    {path:'project.godot',bytes:encode('config_version=5\n\n[application]\nconfig/name="PixelForge Interaction Preview"\nrun/main_scene="res://scene.tscn"\n')},
    {path:'scene.tscn',bytes:encode(scene)},
    {path:'scripts/visibility_rules.gd',bytes:encode(script)},
    {path:'gameplay.json',bytes:encode(JSON.stringify(behavior,null,2)+'\n')},
    {path:'manifest.json',bytes:encode(JSON.stringify(manifest,null,2)+'\n')},
    {path:'README.md',bytes:encode(readme)}
  ];
  return Object.freeze({
    filename:'pixelforge-godot4-interaction-project.zip',
    mime:'application/zip',
    bytes:zipStore(entries),
    report:Object.freeze({status:manifest.status,objects:world.objects.length,
      ruleCount:behavior.rules.length,placeholders:proxies.length})
  });
}
